using System;
using System.Text;

namespace Corona.SourceGeneration;

/// <summary>Small deterministic writer. Always uses LF, independent of the build host.</summary>
internal sealed class CodeWriter
{
    private readonly StringBuilder text = new();
    private int indent;
    public CodeWriter Line(string value = "")
    {
        if (value.Length > 0) text.Append(' ', indent * 4).Append(value);
        text.Append('\n');
        return this;
    }
    public CodeWriter Header() => Line("// <auto-generated/>").Line("#nullable enable").Line();
    public CodeWriter Open(string declaration) { Line(declaration); Line("{"); indent++; return this; }
    public CodeWriter Close()
    {
        if (indent == 0) throw new InvalidOperationException("No open block.");
        indent--; return Line("}");
    }
    public override string ToString()
    {
        if (indent != 0) throw new InvalidOperationException("Unclosed code block.");
        return text.ToString();
    }
}
